"use strict";

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "New_Visuals/modules/projectiles/v2");
const manifest = JSON.parse(fs.readFileSync(path.join(source, "sheets.json"), "utf8"));
const expected = ["cannon", "scatter", "missile", "cryo", "ember", "gravity", "pulse", "flak"];
if (manifest.sheets.map(sheet => sheet.module).join() !== expected.join()) {
  throw new Error("Attack artwork must contain exactly the eight approved v2 sheets");
}

const sheets = manifest.sheets.map(sheet => {
  const png = fs.readFileSync(path.join(source, sheet.png));
  const width = sheet.width * sheet.frames * sheet.exportScale;
  const height = sheet.height * sheet.exportScale;
  if (png.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a" ||
      png.readUInt32BE(16) !== width || png.readUInt32BE(20) !== height) {
    throw new Error(`Invalid dimensions for ${sheet.module}`);
  }
  return {
    module: sheet.module, width: sheet.width, height: sheet.height,
    frames: sheet.frames, anchor: sheet.anchor,
    sha256: crypto.createHash("sha256").update(png).digest("hex"),
    data: "data:image/png;base64," + png.toString("base64")
  };
});
fs.writeFileSync(path.join(root, "attack-vfx-data.js"),
  '// Generated by tools/build-attack-vfx.cjs from approved v2 PNG sheets.\n' +
  'window.ATTACK_VFX_SHEETS = ' + JSON.stringify(sheets) + ';\n');
console.log(`Bundled ${sheets.length} attack sheets (${sheets.reduce((sum, sheet) => sum + sheet.frames, 0)} frames)`);
