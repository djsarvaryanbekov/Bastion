"use strict";

// Technical import only: crop concept sheets to their selected top-down silhouette,
// retain alpha, then embed the transparent exports for the standalone build.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { chromium } = require("playwright");

const root = path.resolve(__dirname, "..");
const sourceRoot = path.resolve(process.argv[2] || root);
const specs = JSON.parse(fs.readFileSync(path.join(root, "enemy-art-manifest.json"), "utf8"));

(async function () {
  const browser = await chromium.launch({ headless: true });
  const data = {};
  const audit = {};
  try {
    const page = await browser.newPage();
    for (const [type, spec] of Object.entries(specs)) {
      const raw = fs.readFileSync(path.join(sourceRoot, "New_Visuals", spec.source));
      const result = await page.evaluate(async ({ source, spec }) => {
        const image = new Image();
        image.src = source;
        await image.decode();
        const [left, top, right, bottom] = spec.crop;
        const width = right - left;
        const height = bottom - top;
        const scan = document.createElement("canvas");
        scan.width = width;
        scan.height = height;
        const context = scan.getContext("2d", { willReadFrequently: true });
        context.drawImage(image, left, top, width, height, 0, 0, width, height);
        const pixels = context.getImageData(0, 0, width, height).data;
        let solidLeft = width, solidTop = height, solidRight = 0, solidBottom = 0;
        for (let y = 0; y < height; y += 1) for (let x = 0; x < width; x += 1) {
          if (pixels[(y * width + x) * 4 + 3] < 128) continue;
          solidLeft = Math.min(solidLeft, x);
          solidTop = Math.min(solidTop, y);
          solidRight = Math.max(solidRight, x + 1);
          solidBottom = Math.max(solidBottom, y + 1);
        }
        if (solidRight <= solidLeft) throw new Error("No opaque pixels found in " + spec.source);
        const padding = 8;
        const trim = [Math.max(0, solidLeft - padding), Math.max(0, solidTop - padding), Math.min(width, solidRight + padding), Math.min(height, solidBottom + padding)];
        const exportWidth = trim[2] - trim[0];
        const exportHeight = trim[3] - trim[1];
        const resolution = Math.min(1, 256 / Math.max(exportWidth, exportHeight));
        const output = document.createElement("canvas");
        output.width = Math.round(exportWidth * resolution);
        output.height = Math.round(exportHeight * resolution);
        const outputContext = output.getContext("2d");
        outputContext.imageSmoothingQuality = "high";
        outputContext.drawImage(scan, trim[0], trim[1], exportWidth, exportHeight, 0, 0, output.width, output.height);
        return {
          sprite: { src: output.toDataURL("image/png"), scale: spec.scale, forward: spec.forward || 0 },
          audit: { sourceSize: [image.width, image.height], sourceCrop: spec.crop, opaqueBoundsInsideCrop: [solidLeft, solidTop, solidRight, solidBottom], finalCropInsideSource: [left + trim[0], top + trim[1], left + trim[2], top + trim[3]], exportSize: [output.width, output.height] }
        };
      }, { source: "data:image/png;base64," + raw.toString("base64"), spec });
      data[type] = result.sprite;
      audit[type] = { source: spec.source, sha256: crypto.createHash("sha256").update(raw).digest("hex"), ...result.audit };
    }
  } finally {
    await browser.close();
  }
  fs.writeFileSync(path.join(root, "enemy-art-data.js"), "// Generated by tools/build-enemy-art.js; edit enemy-art-manifest.json instead.\nwindow.DriftEnemyArtData = " + JSON.stringify(data) + ";\n");
  fs.writeFileSync(path.join(root, "enemy-art-audit.json"), JSON.stringify(audit, null, 2) + "\n");
  console.log("Exported " + Object.keys(data).length + " transparent enemy sprites.");
})().catch(function (error) { console.error(error); process.exitCode = 1; });
