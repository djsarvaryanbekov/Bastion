"use strict";

// Packs locales/<code>.json into locales.js, keeping only keys present in the English catalog.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const localesDirectory = path.join(root, "locales");
const catalog = JSON.parse(fs.readFileSync(path.join(localesDirectory, "en.json"), "utf8"));
const bundle = {};

fs.readdirSync(localesDirectory).filter(file => file.endsWith(".json") && file !== "en.json").sort().forEach(file => {
  const code = file.replace(/\.json$/, "");
  const table = JSON.parse(fs.readFileSync(path.join(localesDirectory, file), "utf8"));
  const packed = {};
  Object.keys(catalog).forEach(key => {
    if (typeof table[key] === "string" && table[key]) packed[key] = table[key];
  });
  bundle[code] = packed;
});

const source = "// Generated by tools/build-locales.cjs from locales/*.json. Do not edit by hand.\n" +
  "window.BastionLocales = " + JSON.stringify(bundle) + ";\n";
fs.writeFileSync(path.join(root, "locales.js"), source, "utf8");
console.log("locales.js: " + (Object.keys(bundle).join(", ") || "no translations"));
