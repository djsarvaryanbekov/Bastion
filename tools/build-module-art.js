"use strict";

// Technical import: mask upper assemblies, crop padding and uniformly downsample.
// Source artwork is never rewritten. Geometry is expressed in tile units.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { chromium } = require("playwright");
const root = path.resolve(__dirname, "..");
const sourceRoot = path.resolve(process.argv[2] || root);
const specs = JSON.parse(fs.readFileSync(path.join(root, "module-art-manifest.json"), "utf8"));

(async function () {
  const browser = await chromium.launch({ headless: true });
  const data = {}, audit = {};
  try {
    const page = await browser.newPage();
    for (const [type, spec] of Object.entries(specs)) {
      const raw = fs.readFileSync(path.join(sourceRoot, "New_Visuals", spec.source));
      const result = await page.evaluate(async ({ spec, source }) => {
        const image = new Image(); image.src = source; await image.decode();
        const scan = document.createElement("canvas");
        scan.width = image.width; scan.height = image.height;
        const context = scan.getContext("2d", { willReadFrequently: true });
        if (spec.movingPolygon) {
          context.beginPath();
          spec.movingPolygon.forEach(function (point, index) { context[index ? "lineTo" : "moveTo"](point[0], point[1]); });
          context.closePath(); context.clip();
        }
        context.drawImage(image, 0, 0);
        const pixels = context.getImageData(0, 0, scan.width, scan.height).data;
        let left = scan.width, top = scan.height, right = 0, bottom = 0, transparent = 0;
        for (let y = 0; y < scan.height; y++) for (let x = 0; x < scan.width; x++) {
          const alpha = pixels[(y * scan.width + x) * 4 + 3];
          if (alpha === 0) transparent++;
          if (alpha < 128) continue;
          left = Math.min(left, x); top = Math.min(top, y);
          right = Math.max(right, x + 1); bottom = Math.max(bottom, y + 1);
        }
        if (!transparent || right <= left) throw new Error("Expected transparent sprite: " + spec.source);
        const bounds = [left, top, right, bottom];
        const pivot = spec.pivot || [(left + right) / 2, (top + bottom) / 2];
        let radius = 0;
        for (let y = Math.max(top, spec.bodyTop || 0); y < bottom; y++) for (let x = Math.max(left, spec.bodyLeft || 0); x < right; x++) {
          if (pixels[(y * scan.width + x) * 4 + 3] >= 128) radius = Math.max(radius, Math.hypot(x - pivot[0], y - pivot[1]));
        }
        const scale = spec.scale || (spec.rotates ? .43 / radius : spec.span / Math.max(right - left, bottom - top));
        const crop = spec.crop || [Math.max(0, left - 2), Math.max(0, top - 2), Math.min(scan.width, right + 2), Math.min(scan.height, bottom + 2)];
        const width = crop[2] - crop[0], height = crop[3] - crop[1];
        const canvas = document.createElement("canvas");
        const resolution = Math.min(1, 256 / Math.max(width, height));
        canvas.width = Math.round(width * resolution); canvas.height = Math.round(height * resolution);
        const output = canvas.getContext("2d"); output.imageSmoothingQuality = "high";
        output.drawImage(scan, crop[0], crop[1], width, height, 0, 0, canvas.width, canvas.height);
        return {
          sprite: { src: canvas.toDataURL("image/png"), x: (crop[0] - pivot[0]) * scale, y: (crop[1] - pivot[1]) * scale, width: width * scale, height: height * scale, rotates: !!spec.rotates, forward: spec.forward || 0, mount: !!spec.mount, integrated: !!spec.integrated },
          audit: { sourceSize: [image.width,image.height], solidBounds: bounds, crop, pivot, tileScale: scale, bodyRadiusInTiles: radius * scale, transparentPixels: transparent, exportSize: [canvas.width,canvas.height] }
        };
      }, { spec, source: "data:image/png;base64," + raw.toString("base64") });
      data[type] = result.sprite;
      audit[type] = { source: spec.source, sha256: crypto.createHash("sha256").update(raw).digest("hex"), ...result.audit };
    }
    fs.writeFileSync(path.join(root, "module-art-data.js"), "// Generated by tools/build-module-art.js; edit module-art-manifest.json instead.\nwindow.DriftModuleArtData = " + JSON.stringify(data) + ";\n");
    fs.writeFileSync(path.join(root, "module-art-audit.json"), JSON.stringify(audit, null, 2) + "\n");
    console.log("Exported " + Object.keys(data).length + " transparent sprites.");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
