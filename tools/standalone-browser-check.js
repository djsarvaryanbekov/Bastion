const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
async function advanceTrainingUntil(page, predicate, label) {
  for (let elapsed = 0; elapsed <= 30000; elapsed += 1000) {
    if (predicate(await page.evaluate(() => window.__driftBastion.getState()))) return;
    await page.clock.runFor(1000);
  }
  assert.fail('Training did not reach ' + label);
}
