const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
(async () => {
  const file = path.resolve('outputs/Drift_Bastion_Playtest.html');
  const html = fs.readFileSync(file, 'utf8');
  const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
  assert.equal(scripts.length, 11);
  for (const script of scripts) new vm.Script(script[1]);
  assert.equal(/<script\b[^>]*src=/.test(html), false);
  const browser = await chromium.launch({ headless: true });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, acceptDownloads: true });
    page.on('pageerror', error => errors.push(error.message));
    await page.clock.install(); await page.goto(pathToFileURL(file).href);
    await page.locator('#startTrainingButton').click();
    assert.equal(await page.locator('#trainingHUD').isVisible(), true);
    assert.equal(await page.locator('#trainingHUD').getAttribute('data-stage'), 'combat');
    assert.equal(await page.locator('#trainingContinueButton, #trainingPracticeButton').count(), 0);
    await page.locator('#trainingOpenBuildButton').click();
    assert.equal(await page.locator('#catalog .catalog-card').count(), 3);
    assert.equal(await page.locator('#trainingBuildBar').isVisible(), true);
    await page.locator('#trainingBuildExitButton').click();
    assert.equal(await page.locator('#menuOverlay').isVisible(), true);
    await page.locator('#startButton').click();
    assert.equal(await page.locator('#onboardingCue').count(), 0);
    assert.equal(await page.locator('#trainingHUD').isVisible(), false);
    assert.equal(await page.locator('#resetProgressButton, #debugToolsToggle, #replayOnboardingButton').count(), 3);
    assert.equal(await page.locator('#retryButton, #trainingStartSurvivalButton').count(), 0);
    assert.equal(await page.locator('#guidePanel, #replayGuideButton, #catalogBrowseButton, #buildUpgradeTab').count(), 0);
    await page.locator('#buildButton').click();
    assert.equal(await page.locator('#catalog .catalog-card').count(), 2);
    await page.locator('.build-cell[data-x="0"][data-y="-1"]').click();
    assert.equal(await page.locator('#buildGrid').isVisible(), true);
    assert.equal(await page.locator('#buildUpgradePanel').isVisible(), true);
    await page.locator('#closeBuild').click();
    await page.locator('#pauseButton').click();
    assert.equal(await page.locator('#restartButton').isVisible(), false);
    const pendingDownload = page.waitForEvent('download');
    await page.locator('#exportTelemetryButton').click();
    const downloaded = await pendingDownload;
    const data = JSON.parse(fs.readFileSync(await downloaded.path(), 'utf8'));
    assert.equal(data.schemaVersion, 2);
    const run = data.runs.at(-1);
    assert.equal(run.metricsVersion, 2);
    assert.equal(run.gameBuild, '2026.09.09-gradual-fragments-12');
    await page.locator('#pauseHangarButton').click();
    await page.clock.runFor(1000);
    assert.equal(await page.locator('#resultOverlay').isVisible(), true);
    await page.locator('#hangarButton').click();
    assert.equal(await page.locator('#hangarOverlay').isVisible(), true);
    assert.equal(await page.locator('#hud').isVisible(), false);
    await page.locator('#closeHangar').click();
    assert.equal(await page.locator('#menuOverlay').isVisible(), true);
    assert.deepEqual(errors, []);
    const report = { passed: true, inlineScripts: scripts.length, fileUrlBoot: true, separateTrainingEntryAndExit: true, resultsReturnThroughHangar: true, newRunShortcutsRemoved: true, localExportSchema: data.schemaVersion, newRunBuild: run.gameBuild, errors };
    fs.mkdirSync('outputs/training-sector-2026-09-09', { recursive: true });
    fs.writeFileSync('outputs/training-sector-2026-09-09/standalone-report.json', JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
